import re
import uuid
from pathlib import Path
from typing import List
from ..models.schemas import Finding, FindingCategory, Severity

ECHO_COMMENT_PATTERNS = [
    (r"(?i)#\s*increment\s+\w+\s*(?:by\s*\d+)?", r"\b\w+\s*\+=\s*\d+"),
    (r"(?i)#\s*set\s+\w+\s+to\s+\w+", r"\b\w+\s*="),
    (r"(?i)#\s*initialize\s+\w+", r"\b\w+\s*="),
    (r"(?i)#\s*return\s+(?:the\s+)?\w+", r"\breturn\b"),
    (r"(?i)//\s*return\s+(?:the\s+)?\w+", r"\breturn\b"),
    (r"(?i)//\s*increment\s+\w+", r"\b\w+\+\+|\b\w+\s*\+="),
    (r"(?i)#\s*import\s+(?:required\s+)?(?:modules|libraries|packages)", r"^(?:import|from)\s+"),
]

AI_ARTIFACT_PATTERNS = [
    (r"(?i)(?:as an ai|here is the code|here's the implementation|generated by (?:copilot|chatgpt|claude|gemini))",
     "AI Prompt / Assistant Artifact in Production Code",
     "Leftover AI assistant conversation artifact or prompt meta-commentary detected in code.",
     Severity.MEDIUM),
    (r"(?i)#\s*Note:\s*Make sure to replace this with your actual",
     "Unreplaced AI Boilerplate Instruction",
     "AI boilerplate placeholder instructing developer to customize code before deployment.",
     Severity.HIGH)
]

REDUNDANT_RE_RAISE = re.compile(r"""(?i)except\s+(\w+)\s+as\s+(\w+):\s*\n\s*raise\s+\2\b""")
REDUNDANT_CATCH_THROW = re.compile(r"""(?i)catch\s*\(\s*(\w+)\s*\)\s*\{\s*throw\s+\1;\s*\}""")
DOUBLE_CAST_PATTERN = re.compile(r"""\b(?:str\s*\(\s*str|int\s*\(\s*int|Boolean\s*\(\s*Boolean)\s*\(""")

def scan_file_slop(file_path: Path, rel_path: str, content: str) -> List[Finding]:
    findings = []
    lines = content.splitlines()

    # 1. AI Conversation Artifacts
    for idx, line in enumerate(lines, 1):
        for pattern, title, desc, sev in AI_ARTIFACT_PATTERNS:
            if re.search(pattern, line):
                snippet = f"{idx}: {line}"
                findings.append(Finding(
                    id=f"slop-{uuid.uuid4().hex[:8]}",
                    title=title,
                    category=FindingCategory.SLOP,
                    severity=sev,
                    file_path=rel_path,
                    line_number=idx,
                    snippet=snippet,
                    explanation=desc,
                    evidence=f"Matched AI marker pattern at line {idx}: `{line.strip()}`",
                    remediation="Clean up conversational commentary and replace placeholder guidelines with concrete logic.",
                    confidence=0.98,
                    verified=True
                ))

    # 2. Echo / Tautological comments
    for idx in range(len(lines) - 1):
        curr_line = lines[idx].strip()
        next_line = lines[idx + 1].strip()
        for comment_pat, code_pat in ECHO_COMMENT_PATTERNS:
            if re.search(comment_pat, curr_line) and re.search(code_pat, next_line):
                snippet = f"{idx+1}: {curr_line}\n{idx+2}: {next_line}"
                findings.append(Finding(
                    id=f"slop-{uuid.uuid4().hex[:8]}",
                    title="Tautological / Echo Comment (AI Slop)",
                    category=FindingCategory.SLOP,
                    severity=Severity.LOW,
                    file_path=rel_path,
                    line_number=idx + 1,
                    snippet=snippet,
                    explanation="Redundant comment that simply restates what the immediate line of code does without adding business context or architectural intent.",
                    evidence=f"Comment `{curr_line}` directly echoes following statement `{next_line}`",
                    remediation="Remove trivial comments or replace them with high-level explanations of *why* the logic is designed this way.",
                    confidence=0.90,
                    verified=True
                ))

    # 3. Redundant try-catch / re-raise
    for match in REDUNDANT_RE_RAISE.finditer(content):
        # find line number
        start_pos = match.start()
        line_no = content[:start_pos].count("\n") + 1
        snippet = match.group(0)
        findings.append(Finding(
            id=f"slop-{uuid.uuid4().hex[:8]}",
            title="Redundant Try-Catch Re-raise Bloat",
            category=FindingCategory.SLOP,
            severity=Severity.LOW,
            file_path=rel_path,
            line_number=line_no,
            snippet=snippet,
            explanation="Exception handler intercepts an exception only to re-raise it without logging, context wrapping, or error recovery.",
            evidence=f"Redundant block: `{snippet.replace(chr(10), ' ')}`",
            remediation="Eliminate the unnecessary try-except block to allow the exception to bubble up naturally.",
            confidence=0.95,
            verified=True
        ))

    # 4. Redundant JS catch-throw
    for match in REDUNDANT_CATCH_THROW.finditer(content):
        start_pos = match.start()
        line_no = content[:start_pos].count("\n") + 1
        snippet = match.group(0)
        findings.append(Finding(
            id=f"slop-{uuid.uuid4().hex[:8]}",
            title="Redundant Catch-and-Rethrow Wrapper",
            category=FindingCategory.SLOP,
            severity=Severity.LOW,
            file_path=rel_path,
            line_number=line_no,
            snippet=snippet,
            explanation="Catch block immediately throws the caught error without remediation or enriched diagnostic details.",
            evidence=f"Redundant catch block at line {line_no}",
            remediation="Remove the wrapping try-catch construct.",
            confidence=0.95,
            verified=True
        ))

    # 5. Redundant Double Casting / Conversion Bloat
    for idx, line in enumerate(lines, 1):
        if DOUBLE_CAST_PATTERN.search(line):
            snippet = f"{idx}: {line.strip()}"
            findings.append(Finding(
                id=f"slop-{uuid.uuid4().hex[:8]}",
                title="Redundant Nested Type Casting",
                category=FindingCategory.SLOP,
                severity=Severity.LOW,
                file_path=rel_path,
                line_number=idx,
                snippet=snippet,
                explanation="Nested duplicate type casts (e.g. `str(str(...))` or `int(int(...))`) indicate copy-paste or AI generation bloat.",
                evidence=f"Duplicate cast on line {idx}: `{line.strip()}`",
                remediation="Simplify expressions to a single type conversion.",
                confidence=0.92,
                verified=True
            ))

    # 6. Duplicate Import statements in the same file
    seen_imports = {}
    for idx, line in enumerate(lines, 1):
        clean = line.strip()
        if (clean.startswith("import ") or clean.startswith("from ")) and not clean.startswith("from __future__"):
            if clean in seen_imports:
                prev_line = seen_imports[clean]
                snippet = f"{prev_line}: {clean} (original)\n...\n{idx}: {clean} (duplicate)"
                findings.append(Finding(
                    id=f"slop-{uuid.uuid4().hex[:8]}",
                    title="Duplicate Module Import",
                    category=FindingCategory.SLOP,
                    severity=Severity.LOW,
                    file_path=rel_path,
                    line_number=idx,
                    snippet=snippet,
                    explanation=f"The statement `{clean}` is imported multiple times in the same source file.",
                    evidence=f"First defined at line {prev_line}, duplicated at line {idx}",
                    remediation="Remove the redundant duplicate import statement.",
                    confidence=0.99,
                    verified=True
                ))
            else:
                seen_imports[clean] = idx

    return findings
